// Extracts the template and logic from LinkeCash.dc.html into TS modules.
import fs from "node:fs";
const dir = new URL("../src/app/linkecash/dc/", import.meta.url);
const src = fs.readFileSync(new URL("LinkeCash.dc.html", dir), "utf8");
const tpl = src.slice(src.indexOf("</helmet>") + 9, src.indexOf("</x-dc>")).trim();
fs.writeFileSync(new URL("template.ts", dir), `// Generated by scripts/build-linkecash.mjs — do not edit.\nexport default ${JSON.stringify(tpl)};\n`);
const m = src.match(/<script type="text\/x-dc"[^>]*>([\s\S]*?)<\/script>/);
const logic = m[1].replace("class Component extends DCLogic", "export class LinkeCashLogic extends DCLogic");
fs.writeFileSync(new URL("logic.ts", dir), `// @ts-nocheck\n// Generated by scripts/build-linkecash.mjs — do not edit.\nimport { DCLogic } from "./runtime";\n${logic}\n`);
// report expressions that are not plain paths
const bad = [...tpl.matchAll(/\{\{\s*([^}]*?)\s*\}\}/g)].map((x) => x[1]).filter((e) => !/^[\w$.]+$/.test(e));
console.log("non-path expressions:", bad);
